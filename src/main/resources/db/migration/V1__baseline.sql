CREATE TABLE pricing_rate (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hourly_rate numeric(10,2) NOT NULL,
  base_fee numeric(10,2) NOT NULL,
  min_floor numeric(10,2) NOT NULL,
  mode varchar(255) NOT NULL
);

CREATE TABLE material (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(255),
  cost_per_gram numeric(10,2) NOT NULL
);

CREATE TABLE users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar(255) NOT NULL UNIQUE,
  password_hash varchar(255)
);

CREATE TABLE upload (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  original_filename varchar(255),
  status varchar(255) NOT NULL,
  error_message varchar(255),
  print_seconds bigint,
  filament_cm3 numeric(38,2),
  slicer_version varchar(255),
  material_id bigint REFERENCES material(id),
  estimated_price numeric(38,2),
  created_at timestamp(6) with time zone,
  owner_id bigint,
  stored_filename varchar(255),
  price_breakdown varchar(4000)
);
