package com.example.costestimator.service;

import java.io.IOException;
import java.math.BigDecimal;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;
import java.util.Comparator;
import java.util.List;
import java.util.concurrent.Semaphore;
import java.util.concurrent.TimeUnit;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.core.io.ClassPathResource;
import org.springframework.stereotype.Service;

@Service
public class SlicerRunner {

  private static final Pattern TIME = Pattern
      .compile("estimated printing time \\(normal mode\\) = (?:([\\d]+)h\\s*)?(?:([\\d]+)m\\s*)?(\\d+)s");
  private static final Pattern CM3 = Pattern.compile("filament used \\[cm3\\] = ([\\d.]+)");
  private static final Pattern VERSION = Pattern.compile("generated by PrusaSlicer (\\S+)");
  private static final Logger log = LoggerFactory.getLogger(SlicerRunner.class);

  private final String slicerPath;
  private final String profilePath;
  private final Duration timeout;
  private final Semaphore slots;

  public SlicerRunner(
      @Value("${slicer.path:prusa-slicer}") String slicerPath,
      @Value("${slicer.profile:minimal.ini}") String profilePath,
      @Value("${slicer.timeout:120s}") Duration timeout,
      @Value("${slicer.max-concurrent:2}") int maxConcurrent) {
    this.slicerPath = slicerPath;
    this.profilePath = profilePath;
    this.timeout = timeout;
    this.slots = new Semaphore(maxConcurrent);
  }

  public SliceResult slice(Path stlPath) {
    if (!slots.tryAcquire()) {
      throw new IllegalStateException("slicer busy, try again later");
    }
    try {
      return doSlice(stlPath);
    } finally {
      slots.release();
    }
  }

  private SliceResult doSlice(Path stlPath) {
    Path tmpDir = null;
    try {
      tmpDir = Files.createTempDirectory("slice-");
      Path profile = copyProfileTo(tmpDir);
      Path out = tmpDir.resolve("out.gcode");
      Path logFile = tmpDir.resolve("slicer.log");

      List<String> cmd = List.of(
          slicerPath,
          "-g",
          "--load", profile.toString(),
          "--output", out.toString(),
          stlPath.toAbsolutePath().toString());
      log.info("running slicer: {}", String.join(" ", cmd));

      ProcessBuilder pb = new ProcessBuilder(cmd);
      pb.redirectErrorStream(true);
      pb.redirectOutput(logFile.toFile());
      Process proc = pb.start();
      try {
        boolean finished = proc.waitFor(timeout.toSeconds(), TimeUnit.SECONDS);
        if (!finished) {
          throw new IllegalStateException("slicer timed out after " + timeout);
        }
        String output = Files.readString(logFile);
        if (proc.exitValue() != 0) {
          throw new IllegalStateException("slicer failed (exit " + proc.exitValue() + "): " + output);
        }
        if (!Files.exists(out)) {
          throw new IllegalStateException("slicer produced no output: " + output);
        }
        return parse(Files.readString(out));
      } finally {
        if (proc.isAlive()) {
          killTree(proc);
        }
      }
    } catch (IOException e) {
      throw new IllegalStateException("could not run slicer: " + e.getMessage(), e);
    } catch (InterruptedException e) {
      Thread.currentThread().interrupt();
      throw new IllegalStateException("interrupted while slicing", e);
    } finally {
      deleteRecursively(tmpDir);
    }
  }

  public SliceResult parse(String gcode) {
    Matcher t = TIME.matcher(gcode);
    if (!t.find()) {
      throw new IllegalStateException("no print time in gcode");
    }
    Matcher c = CM3.matcher(gcode);
    if (!c.find()) {
      throw new IllegalStateException("no filament volume in gcode");
    }
    Matcher v = VERSION.matcher(gcode);
    long h = t.group(1) == null ? 0 : Long.parseLong(t.group(1));
    long m = t.group(2) == null ? 0 : Long.parseLong(t.group(2));
    long s = Long.parseLong(t.group(3));
    return new SliceResult(
        h * 3600 + m * 60 + s,
        new BigDecimal(c.group(1)),
        v.find() ? v.group(1) : "unknown");
  }

  private Path copyProfileTo(Path dir) throws IOException {
    try (var in = new ClassPathResource(profilePath).getInputStream()) {
      Path target = dir.resolve("profile.ini");
      Files.copy(in, target);
      return target;
    }
  }

  private void killTree(Process proc) {
    proc.descendants().forEach(ProcessHandle::destroyForcibly);
    proc.destroyForcibly();
  }

  private void deleteRecursively(Path dir) {
    if (dir == null) {
      return;
    }
    try (var paths = Files.walk(dir)) {
      paths.sorted(Comparator.reverseOrder()).forEach(p -> {
        try {
          Files.deleteIfExists(p);
        } catch (IOException ignored) {
        }
      });
    } catch (IOException ignored) {
    }
  }
}
